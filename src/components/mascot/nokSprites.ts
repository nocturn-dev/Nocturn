/**
 * Пиксель-матрицы Нока — светлячка-маскота Nocturn. Спрайты живут кодом
 * (а не картинками): палитра клеток резолвится в theme-токены на рендере,
 * маскот автоматически перекрашивается во всех темах, включая
 * Official-монохром, где цвет остаётся только у семантики.
 *
 * Клетки:
 *   . — пусто
 *   a — усик (accent)
 *   b — тело (deep — тёмный силуэт, читается на любом фоне за счёт свечения)
 *   e — глаз (text — светлая точка внутри тёмной головы)
 *   G — лампа сильная (accent ~85%)
 *   g — лампа мягкая (accent ~32%)
 *   w — крылышки (muted, мерцают)
 */

export const NOK_COLS = 10;
export const NOK_ROWS = 10;

/** Клетка спрайта на экране — 3px, высота растёт с масштабом */
const NOK_CELL = 3;
/** Оптическая поправка посадки: лапы на кромке шелла композера */
const PERCH_LIP = 3;

/** top обёртки Нока на насесте: baseOffset — где у контейнера «пол» (в
 *  ChatArea это кромка шелла, в превью настроек — верх мока композера).
 *  Формула общая, чтобы посадка в превью не разъехалась с настоящей */
export function nokPerchTop(size: number, baseOffset: number): number {
  return baseOffset - NOK_ROWS * NOK_CELL * size + PERCH_LIP;
}

/** Базовый кадр: усики, голова, глаза, крылышки по бокам, брюшко-лампа */
export const NOK_BASE = [
  ".a.....a..",
  "..a...a...",
  "..bbbb....",
  "wbbbbbb.w.",
  "wbebbeb.w.",
  "wbbbbbb.w.",
  "..bbbb....",
  ".GGGGGG...",
  "GGGGGGGG..",
  ".GGGGGG...",
];

/** Кадр с закрытыми глазами (моргание/сон) — глаза в цвет тела */
export const NOK_BLINK = NOK_BASE.map((row, y) =>
  y === 4 ? row.replace(/e/g, "b") : row,
);

