/**
 * Пиксель-матрицы Нока — светлячка-маскота Nocturn. Спрайты живут кодом
 * (а не картинками): палитра клеток резолвится в theme-токены на рендере,
 * маскот автоматически перекрашивается во всех темах, включая
 * Official-монохром, где цвет остаётся только у семантики.
 *
 * Клетки:
 *   . — пусто
 *   a — усик (accent)
 *   b — тело (deep — тёмный силуэт, читается на любом фоне за счёт свечения)
 *   e — глаз (bg — светлая точка внутри тёмной головы)
 *   G — лампа сильная (accent ~85%)
 *   g — лампа мягкая (accent ~32%)
 */

export const NOK_COLS = 10;
export const NOK_ROWS = 10;

/** Базовый кадр: усики, голова, глаза, светящееся брюшко-лампа */
export const NOK_BASE = [
  ".a.....a..",
  "..a...a...",
  "..bbbb....",
  ".bbbbbb...",
  ".bebbeb...",
  ".bbbbbb...",
  "..bbbb....",
  ".GGGGGG...",
  "GGGGGGGG..",
  ".GGGGGG...",
];

/** Кадр с закрытыми глазами (моргание/сон) — глаза в цвет тела */
export const NOK_BLINK = NOK_BASE.map((row, y) =>
  y === 4 ? row.replace(/e/g, "b") : row,
);
